import fs from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
const db = new DatabaseSync(':memory:');
for (const file of fs.readdirSync('drizzle').filter(f => f.endsWith('.sql')).sort())
  db.exec(fs.readFileSync('drizzle/' + file, 'utf8'));
const quote = (name) => '"' + name.replaceAll('"', '""') + '"';
const statements = [
  `CREATE OR REPLACE FUNCTION session_json_extract(input text, field text) RETURNS text
   LANGUAGE sql IMMUTABLE AS $$ SELECT input::jsonb ->> field $$`,
  `CREATE OR REPLACE FUNCTION session_json_array_length(input text, field text) RETURNS integer
   LANGUAGE sql IMMUTABLE AS $$ SELECT jsonb_array_length(input::jsonb -> field) $$`,
  `CREATE OR REPLACE FUNCTION session_json_each(input text) RETURNS TABLE(value text)
   LANGUAGE sql IMMUTABLE AS $$ SELECT item #>> '{}' FROM jsonb_array_elements(input::jsonb) item $$`,
];
const tables = db.prepare("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'").all();
for (const table of tables) {
  const columns = db.prepare(`PRAGMA table_info(${quote(table.name)})`).all();
  const primary = columns.filter(c => c.pk).sort((a,b) => a.pk-b.pk);
  const definitions = columns.map(c => {
    const auto = table.sql.includes('AUTOINCREMENT') && c.pk;
    return `${quote(c.name)} ${c.type.toLowerCase() === 'integer' ? 'BIGINT' : 'TEXT'}${auto ? ' GENERATED BY DEFAULT AS IDENTITY' : ''}${c.notnull || c.pk ? ' NOT NULL' : ''}${c.dflt_value !== null ? ' DEFAULT ' + c.dflt_value : ''}`;
  });
  if (primary.length) definitions.push(`PRIMARY KEY (${primary.map(c=>quote(c.name)).join(',')})`);
  for (const index of db.prepare(`PRAGMA index_list(${quote(table.name)})`).all().filter(i=>i.origin==='u')) {
    const cols = db.prepare(`PRAGMA index_info(${quote(index.name)})`).all();
    definitions.push(`UNIQUE (${cols.map(c=>quote(c.name)).join(',')})`);
  }
  statements.push(`CREATE TABLE IF NOT EXISTS ${quote(table.name)} (\n  ${definitions.join(',\n  ')}\n)`);
}
for (const index of db.prepare("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL").all())
  statements.push(index.sql.replace(/`([^`]+)`/g, '"$1"').replace('CREATE UNIQUE INDEX ', 'CREATE UNIQUE INDEX IF NOT EXISTS ').replace(/^CREATE INDEX /, 'CREATE INDEX IF NOT EXISTS '));
statements.push(`CREATE TABLE IF NOT EXISTS upload_sessions (
  id TEXT PRIMARY KEY, owner TEXT NOT NULL, metadata TEXT NOT NULL, size BIGINT NOT NULL,
  parts BIGINT NOT NULL, expires BIGINT NOT NULL, status TEXT NOT NULL DEFAULT 'pending')`);
statements.push('CREATE INDEX IF NOT EXISTS upload_sessions_owner ON upload_sessions(owner)');
fs.mkdirSync('deploy', {recursive:true});
fs.writeFileSync('deploy/001-session-postgres.sql', '-- Generated from the final append-only D1 migrations. Fresh SESSION database only.\n' + statements.join(';\n\n') + ';\n');
console.log(`Generated ${tables.length} tables and ${statements.length} statements.`);
